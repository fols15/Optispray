export const LANGS = ["en", "kk"];

// Number format by language, done here rather than with Intl because some
// browsers ship without Kazakh number data. English: 14,300,000.5  Kazakh: 14 300 000,5
export const NUMBER_FORMAT = { en: { group: ",", decimal: "." }, kk: { group: "\u00a0", decimal: "," } };
export function formatNumber(n, digits, lang) {
  const f = NUMBER_FORMAT[lang] || NUMBER_FORMAT.en;
  const [int, frac] = Math.abs(n).toFixed(digits).split(".");
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, f.group);
  return (n < 0 ? "\u2212" : "") + grouped + (frac ? f.decimal + frac : "");
}
